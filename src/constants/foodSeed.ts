export function getSeedFoods(countryCode: CountryCode, city: string): FoodItem[] {
  const currency: CurrencyCode = countryCode === 'PK' ? 'PKR' : 'INR';
  const factor = cityFactors[city] ?? 1;
  const observedAt = new Date().toISOString();
  const validUntil = new Date(Date.now() + 30 * 24 * 60 * 60 * 1000).toISOString();

  return foods.map(f => ({
    id: f.id,
    canonicalName: f.id,
    nameEn: f.nameEn,
    nameUr: f.nameUr,
    nameRomanUr: f.nameRomanUr,
    nameHi: f.nameHi ?? null,
    category: f.category,
    dietaryTags: f.tags,
    allergenTags: f.allergens,
    mealTypes: f.meals,
    caloriesPer100g: f.kcal,
    proteinPer100g: f.protein,
    carbsPer100g: f.carbs,
    fatPer100g: f.fat,
    fiberPer100g: f.fiber,
    servingName: f.serving,
    servingGrams: f.servingGrams,
    pricePerKg: Math.round((countryCode === 'PK' ? f.pkrKg : f.inrKg) * factor),
    currencyCode: currency,
    priceSource: 'Seed estimate — verify local market price',
    priceObservedAt: observedAt,
    priceValidUntil: validUntil,
    sourceName: 'Seed starter dataset (USDA/IFCT-derived, verify before production)',
    verified: false,
    instructions: f.instructions,
  })) as FoodItem[];
}

